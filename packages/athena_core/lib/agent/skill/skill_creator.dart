# Skill 创建助手

将具体任务、领域知识或工作流程整理成可复用的 Skill，完成内容设计、资源组织、保存和验证。

## 设计原则

**提供有用的增量知识。** 假设执行者已经具备通用能力，重点写业务背景、判断依据、
关键约束和容易出错的操作。每段内容都应帮助执行者作出更好的决定。

**让细节服务于任务。** 开放任务说明目标和判断标准；有明确做法的任务给出推荐步骤；
顺序敏感或必须精确复现的操作使用详细步骤或脚本。根据任务选择结构和细节程度。

**区分任务要求与偶然情况。** 保留用户的实际目标和业务规则；示例用于解释做法，
某次纠正用于修复具体问题，不把单个案例扩展成适用于所有任务的要求。

**按需展开信息。** 名称和描述负责发现技能，SKILL.md 负责核心流程，支持资源承载
特定场景才需要的细节。让执行者只读取当前任务所需的内容。

## 文件结构与资源选择

```text
skill-name/
├── SKILL.md        必需：元数据与核心指令
├── scripts/        可选：可重复执行的程序
├── references/     可选：按需读取的说明与资料
└── assets/         可选：用于生成结果的模板或素材
```

简单技能只需 SKILL.md。根据具体用途选择支持资源：

- scripts/：适合反复重写的代码、确定性转换或需要可靠复现的操作。
  例如批量转换文件的脚本；在正文中说明输入、调用方式和输出。
- references/：适合数据结构、业务规则、API 说明、较长示例或分场景流程。
  例如数据库 schema 或不同发布目标的操作指南；在入口中链接并说明何时读取。
- assets/：适合交付物需要用到的模板、图片或项目骨架。
  例如报告模板；说明如何使用，不把素材当成必须加载的指令。

同一份信息保留一个维护位置。较长的参考资料可提供目录或检索词；
只有在某个分支需要时才加载它，而不是在入口要求读完全部资源。
例如一个部署技能可以在 SKILL.md 中说明如何选择平台，再链接各平台的独立指南。

## 创建或改进流程

### 1. 明确实际用途

从当前对话、用户材料或已有技能中确定：

- 用户会用什么请求触发技能。
- 执行时有什么输入、依赖和业务约束。
- 应交付什么结果，以及怎样判断完成。

信息不足时询问会影响设计的关键问题。具体请求比抽象功能列表更有用；
已有明确场景时即可开始设计。修改现有技能前，先读取正文和相关资源，
确定需要改进的是触发描述、执行流程、资源内容还是验证方式。

### 2. 编写名称与描述

名称使用小写字母、数字和连字符，不超过 64 个字符，与目录名一致。
优先选简短、体现用途的名称；创建前检查是否已经存在同名技能。

description 同时说明“做什么”和“什么时候用”。模型在加载正文之前依靠它选择技能，
因此把触发场景放在描述中，把详细步骤放在正文中。

例如，“根据会议记录提取决策、负责人和待办；在用户需要会议总结时使用”
比“专业高效的办公助手”更容易被准确选中。只有容易与相邻任务混淆时，才补充适用边界。

### 3. 编写 SKILL.md

文件以 YAML front matter 开头，至少包含非空字符串 name 和 description，
之后是 Markdown 指令。引用、冒号、换行等内容需要符合 YAML 语法。

```markdown
---
name: "meeting-summary"
description: "根据会议记录提取决策和待办；在用户需要会议总结时使用。"
---

# 会议总结

从用户提供的会议记录中提取已确认的决策和待办。
每项待办列出负责人、截止时间和原文依据；缺失的信息标为未明确。
```

正文应让另一个执行者拿到技能后就能完成任务：说明必要输入、关键决策、执行步骤、
输出形式和完成标准。把不明显的业务知识写清楚，示例用于消除真实歧义。
多种处理方式共享的内容放在入口，各自较长的细节放进参考资料。

资源路径相对于技能目录。正文中引用每项必要资源并说明用途；
只有存在重复工作或可靠性收益时才增加脚本。修改现有技能时保留仍然有效的内容和元数据，
移除资源前检查它是否仍被引用。

### 4. 保存文件

使用 skill 工具返回的 User skills directory 作为技能根目录。
用现有文件工具保存 <技能根目录>/<name>/SKILL.md，并保存所需的脚本、参考资料和素材。
如果用户指定了其他交付位置，按指定位置保存并说明位置。

### 5. 验证与迭代

分别检查格式、可用性和实际效果：

- 格式：YAML 可解析，必需字段完整，名称与目录一致，正文没有未完成的占位内容。
- 可用性：按名称用 skill 重新加载并核对内容；检查资源引用、脚本依赖和输入输出。
  保存到其他交付位置时，直接读取文件检查，并区分文件已保存与当前环境已加载。
- 效果：用一个真实的典型请求检查步骤是否足以得到预期结果；
  描述容易误触发时，再用一个相近但不适用的请求检查边界。
  新增或修改的脚本需要实际运行，检查结果而不只检查命令是否成功。

格式通过不等于工作流程有效。依据发现的问题修改对应部分，再验证受影响的行为。
后续根据试用反馈继续改进，优先修正已有指令中的缺口或歧义。

完成后简要说明保存位置、技能用途、验证结果，并给出一条可以直接尝试的请求。
''',
);
