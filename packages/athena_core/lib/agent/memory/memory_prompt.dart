import 'package:athena_core/agent/skill/skill_loader.dart';

/// 经验记忆系统的引导提示词。
///
/// 设计原则：避免 prompt 膨胀。
/// - `hint`：极简提示（~30 token），每次对话注入，告知 Agent 有记忆能力
/// - `fullBody`：完整使用指南，作为内置 `memory` Skill 的 body，按需加载
///
/// 这里**只有经验**：技能的创建与角色提示词的改写是用户的编辑权，不属于
/// Agent 的自主能力。技能仍可由用户手写并通过 `skill` 加载，角色仍可由用户
/// 在设置里编辑。
abstract final class MemoryPrompt {
  /// 极简提示：始终注入，几乎不占 token 预算，仅告知能力的存在。
  ///
  /// 详细指导通过内置 `memory` skill 按需加载。
  static const String hint =
      '你有经验记忆工具：experience_learn、experience_recall。'
      '每个任务开始时会注入当前有效的记忆目录；需要支持性上下文或标签时，'
      '调用 experience_recall。加载 "memory" 技能，了解何时及如何记录经验。'
      '经验默认按角色隔离，仅对通用用户偏好或沟通风格使用 scope="shared"。';

  /// 完整使用指南：仅在 Agent 主动加载 memory skill 时注入。
  ///
  /// 这是内置 Skill 的 body 内容。
  static const String fullBody = '''
经验记忆让你跨会话保留教训与偏好。它记录的是**可能有用**的参考，
不是必须遵守的规则——真正必须遵守的约定属于用户的项目文档与角色定义，
那些由用户维护，不由你改写。

### 何时记录（`experience_learn`）
- **用户纠正你时**：这是最强的信号，记下被纠正的做法与正确做法。
- **你验证出一个反直觉的事实**：例如某框架的真实行为与文档不符、某个坑
  只有实测才能发现。
- **某个做法在多次任务中被证明有效**。

**不要记录**：
- 本次任务具体做了什么（"我改了 X 文件、加了 Y 参数"）——那是变更日志，
  代码库和提交历史里已有，且会随代码演进迅速过期。
- 一次性的、只对当前任务成立的事实。
- 原始错误信息、密钥、文件内容。
- **与已有经验重复的内容**。记录前先看注入的目录里是否已经讲过同一件事；
  措辞不同也算重复。若有，用 `action="update"` 修订那条，而不是新增。

### 何时回忆（`experience_recall`）
- 开始复杂或熟悉的任务前。
- 当前上下文表明以往经验可能适用时。
- 任务开始时已注入全部有效经验的摘要；某条经验适用时，再回忆其支持性
  上下文和标签。

### 作用域
- 默认 `scope="self"`，仅当前角色可见。
- 用户的通用偏好、沟通风格、个人信息，或其他角色也应了解的跨领域模式，
  用 `scope="shared"`。
- 工具专用技巧、领域专属模式不要设为共享，它们会成为其他角色的噪声。

### 写法
- 具体、可执行：说明适用情境、发生过什么、以后该如何调整。
- lesson 不超过 500 字符；支持性细节放入 context。

### 纠正与清理
- 用户指出某条经验已过时或错误时，用 `action="update"` 修订，或用
  `action="archive"` 停用。
- 把基于事实或具有时效性的结论记录为经验前，先用 web_search 核实；
  仅从自身实践得出的经验可能强化自己的盲点。
- **目录有容量上限**：装满后 `experience_learn` 会拒绝新增并列出最旧的候选。
  此时先归档已被取代的教训（`action="archive"`），再重试；不要反复重试
  同一次写入。
''';
}

/// 内置 `memory` Skill：代码注册，不来自磁盘。
///
/// 每个前端的装配层都要注册它（GUI 的 `di.dart`、TUI 的 `tui_di.dart`），
/// 定义放这里而不是各写一份，避免描述文案在两处漂移。
const Skill kMemorySkill = Skill(
  name: 'memory',
  description: '经验记忆指南：何时记录、何时回忆、如何纠正与清理',
  body: MemoryPrompt.fullBody,
  sourcePath: '(builtin)',
);
